BEGIN;

CREATE TABLE IF NOT EXISTS atlas_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
    name_key TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL DEFAULT 'Uncategorized',
    evidence_status TEXT NOT NULL CHECK (evidence_status IN ('evidence_found', 'manually_added')),
    source_type TEXT NOT NULL CHECK (source_type IN ('repository_detected', 'manually_added')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_atlas_skills_name ON atlas_skills (name_key);

CREATE TABLE IF NOT EXISTS atlas_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    name_key TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    repository_url TEXT,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'in_progress', 'completed', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (repository_url IS NULL OR length(repository_url) <= 2048)
);

CREATE INDEX IF NOT EXISTS idx_atlas_projects_name ON atlas_projects (name_key);

CREATE TABLE IF NOT EXISTS atlas_skill_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES atlas_skills(id) ON DELETE CASCADE,
    source_type TEXT NOT NULL CHECK (source_type IN ('repository_detected', 'manually_added')),
    evidence_reference TEXT NOT NULL DEFAULT '',
    detail TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (skill_id, source_type, evidence_reference)
);

CREATE INDEX IF NOT EXISTS idx_atlas_evidence_skill ON atlas_skill_evidence (skill_id);

CREATE TABLE IF NOT EXISTS atlas_project_skills (
    project_id BIGINT NOT NULL REFERENCES atlas_projects(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES atlas_skills(id) ON DELETE CASCADE,
    evidence_reference TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (project_id, skill_id, evidence_reference)
);

CREATE INDEX IF NOT EXISTS idx_atlas_project_skills_skill ON atlas_project_skills (skill_id);

