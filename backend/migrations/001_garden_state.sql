BEGIN;

CREATE TABLE IF NOT EXISTS guestbook_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(60),
    dream_message VARCHAR(1000) NOT NULL CHECK (length(trim(dream_message)) BETWEEN 1 AND 1000),
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS garden_states (
    visitor_id UUID PRIMARY KEY,
    revision INTEGER NOT NULL CHECK (revision >= 1),
    state JSONB NOT NULL CHECK (jsonb_typeof(state) = 'object'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_guestbook_approved_created
    ON guestbook_entries (created_at DESC, id DESC)
    WHERE status = 'approved';

COMMIT;
